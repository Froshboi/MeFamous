-- provider is active, not specifically Owlet.
update public.app_settings set key = 'provider_auto_sync_enabled'
  where key = 'owlet_auto_sync_enabled'
  and not exists (select 1 from public.app_settings where key = 'provider_auto_sync_enabled');

insert into public.app_settings (key, value)
values ('provider_auto_sync_enabled', 'false'::jsonb)
on conflict (key) do nothing;
